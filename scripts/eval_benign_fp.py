"""
LateralX Benign FP Evaluation -- Behavioral Rules Against 60K Synthetic Baseline

Purpose
-------
Measure the False-Positive rate of all Layer B behavioral rules when run against
100% benign synthetic data generated by the ml_synthetic module.  The goal is to
identify which rules fire on legitimate enterprise activity (acceptable statistical
behaviour) versus rules that should NEVER fire on clean data (genuine FP bugs).

The 60,313-event baseline covers 64 users across 77 hosts over 29 days, drawn from
realistic AD profiles: standard_worker, it_admin, service_account, developer,
help_desk, db_admin, executive, domain_controller, security_analyst, cloud_workstation.

Methodology
-----------
  FP alarm  = any anomaly emitted by analyze_behavior on purely benign events
  FP rate   = anomalies per entity per day  (normalises for dataset size)

Rule taxonomy used in the verdict column:
  STATISTICAL  -- rule uses a relative threshold (Z-score, sliding window) that is
                 calibrated to fire at a predictable rate even on benign data.
                 E.g. hourly_event_spike fires at ~2.5% of user-hours by design.
  NEVER-FIRE   -- rule matches a forensic keyword (sekurlsa, vssadmin delete shadows,
                 bcdedit recoveryenabled) that cannot appear in benign events.
                 Any firing here is a genuine false positive in the generator.
  BEHAVIORAL   -- rule fires on event-sequence patterns (EID 10 -> EID 4624 Type 9,
                 EID 4624 Type 3 to ≥3 hosts) that may occasionally appear in benign
                 admin or help-desk activity; a low rate is acceptable.

Usage
-----
  python scripts/eval_benign_fp.py

Output format
-------------
  1. Per-rule firing summary table
  2. Per-entity breakdown (which users/hosts triggered which rules)
  3. Summary statistics: window hours, FP/entity/day, overall verdict
"""

import sys
from collections import defaultdict

sys.path.insert(0, ".")

from backend.analysis.ml_synthetic import generate_baseline_events
from backend.analysis.behavioral import analyze_behavior

# -- Rule taxonomy -------------------------------------------------------------
# Classify every anomaly_type produced by analyze_behavior.
# STATISTICAL  -> designed to fire at a predictable rate (Z-score / density window)
# NEVER-FIRE   -> keyword-only; cannot trigger on benign data without a generator bug
# BEHAVIORAL   -> event-sequence pattern; low rate on benign is acceptable

_RULE_TAXONOMY: dict[str, str] = {
    # Check 1
    "hourly_event_spike":              "STATISTICAL",
    # Check 2
    "lateral_velocity":                "BEHAVIORAL",
    # Check 3
    "auth_failure_burst":              "BEHAVIORAL",
    # Check 4
    "off_hours_privilege":             "BEHAVIORAL",
    # Check 5
    "kerberos_ticket_spike":           "BEHAVIORAL",
    # Check 6
    "group_modification_burst":        "BEHAVIORAL",
    # Check 7
    "privileged_account_creation_chain": "BEHAVIORAL",
    # Check 8
    "ntlm_spike":                      "BEHAVIORAL",
    # Check 9
    "ransomware_recovery_destruction": "NEVER-FIRE",
    # Check 10
    "ntlm_brute_force":                "BEHAVIORAL",
    # Check 11
    "pass_the_hash":                   "BEHAVIORAL",
    # Check 12
    "wmi_shell_spawn":                 "BEHAVIORAL",
    # Check 13
    "event_log_clearing":              "NEVER-FIRE",
    # Check 14
    "lsass_pth_correlation":           "BEHAVIORAL",
    # Check 15a
    "golden_ticket":                   "BEHAVIORAL",
    # Check 15b
    "silver_ticket":                   "BEHAVIORAL",
    # Check 16
    "smb_lateral_movement":            "BEHAVIORAL",
    # Check 17
    "pass_the_ticket":                 "BEHAVIORAL",
    # Check 18
    "rdp_lateral_movement":            "BEHAVIORAL",
    # Check 0 (high-confidence single-event keywords)
    "shadow_copy_deletion":            "NEVER-FIRE",
    "boot_recovery_disabled":          "NEVER-FIRE",
    "certutil_download":               "NEVER-FIRE",
    "bitsadmin_download":              "NEVER-FIRE",
    "mshta_remote_exec":               "NEVER-FIRE",
    "regsvr32_remote_exec":            "NEVER-FIRE",
    "encoded_powershell":              "NEVER-FIRE",
    "mimikatz_invocation":             "NEVER-FIRE",
    "dcsync_invocation":               "NEVER-FIRE",
    "lsass_dump_tool":                 "NEVER-FIRE",
    "pass_the_hash_keyword":           "NEVER-FIRE",
}

_SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "none": 4}


def _verdict(anomaly_type: str, count: int) -> str:
    """
    Return a human-readable verdict for the summary table.
    STATISTICAL rules firing is expected; NEVER-FIRE rules firing is a bug.
    """
    taxonomy = _RULE_TAXONOMY.get(anomaly_type, "BEHAVIORAL")
    if taxonomy == "NEVER-FIRE":
        if count == 0:
            return "OK  -- correctly silent on benign data"
        return f"GENUINE FP -- NEVER-FIRE rule fired {count}x on benign data (generator bug)"
    if taxonomy == "STATISTICAL":
        return f"EXPECTED -- Z-score rule; ~2.5% of user-hours exceed threshold by design"
    # BEHAVIORAL
    if count == 0:
        return "OK  -- no benign activations"
    return f"LOW-RATE FP -- {count} activations; review entity breakdown below"


def main() -> None:
    # -- Step 1: generate baseline ---------------------------------------------
    print("=" * 76)
    print("LateralX Benign FP Evaluation -- Layer B Behavioral Rules")
    print("=" * 76)
    print("\nGenerating 60K synthetic benign baseline events ...", flush=True)

    events = generate_baseline_events()
    print(f"Generated {len(events):,} events.")

    if not events:
        print("ERROR: generate_baseline_events() returned empty list.")
        sys.exit(1)

    # -- Step 2: compute analysis window ---------------------------------------
    sorted_events = sorted(events, key=lambda e: e.timestamp)
    t_start = sorted_events[0].timestamp
    t_end   = sorted_events[-1].timestamp
    span_hours = (t_end - t_start).total_seconds() / 3600
    span_days  = span_hours / 24

    unique_users = {e.user for e in events if e.user and not (e.user or "").endswith("$")}
    unique_hosts = {e.source_host for e in events}
    n_entities   = len(unique_users) + len(unique_hosts)

    print(f"\nDataset summary")
    print(f"  Events        : {len(events):,}")
    print(f"  Unique users  : {len(unique_users)}")
    print(f"  Unique hosts  : {len(unique_hosts)}")
    print(f"  Time range    : {t_start.strftime('%Y-%m-%d %H:%M')} -> "
          f"{t_end.strftime('%Y-%m-%d %H:%M')}")
    print(f"  Window (h)    : {span_hours:,.1f}  ({span_days:.1f} days)")

    # -- Step 3: run analyze_behavior on all events ----------------------------
    print("\nRunning analyze_behavior on all events ...", flush=True)
    result   = analyze_behavior(events)
    anomalies = result.get("anomalies", [])
    print(f"analyze_behavior returned {len(anomalies)} anomalies total.")

    # -- Step 4: aggregate per rule --------------------------------------------
    by_type: dict[str, list[dict]] = defaultdict(list)
    for a in anomalies:
        by_type[a["anomaly_type"]].append(a)

    # Collect all anomaly types (fired + known-never-fire)
    all_known_types = sorted(_RULE_TAXONOMY.keys())
    fired_types     = sorted(by_type.keys())
    all_types       = sorted(set(all_known_types) | set(fired_types))

    # -- Step 5: per-entity breakdown ------------------------------------------
    entity_rule_map: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for a in anomalies:
        entity = a.get("entity", "__unknown__")
        atype  = a["anomaly_type"]
        desc   = a.get("description", "")[:120]
        entity_rule_map[entity][atype].append(desc)

    # -- Step 6: FP rate -------------------------------------------------------
    total_fp_alarms = len(anomalies)
    fp_per_entity_per_day = (
        total_fp_alarms / max(n_entities, 1) / max(span_days, 1)
    )

    # -- Step 7: print summary table -------------------------------------------
    print(f"\n{'-' * 76}")
    print(f"{'Anomaly Type':<38} {'Count':>5}  {'Entities':>8}  {'Sev':>4}  Verdict")
    print(f"{'-' * 76}")

    never_fire_fired = 0
    for atype in all_types:
        items    = by_type.get(atype, [])
        count    = len(items)
        entities = len({a.get("entity", "") for a in items})
        sev_vals = [_SEVERITY_ORDER.get(a.get("severity", "none"), 4) for a in items]
        sev_min  = min(sev_vals) if sev_vals else 4
        sev_str  = {0: "CRIT", 1: "HIGH", 2: "MED", 3: "LOW", 4: "--"}.get(sev_min, "--")
        verdict  = _verdict(atype, count)

        taxonomy = _RULE_TAXONOMY.get(atype, "BEHAVIORAL")
        if taxonomy == "NEVER-FIRE" and count > 0:
            never_fire_fired += count

        print(f"  {atype:<36} {count:>5}  {entities:>8}  {sev_str:>4}  {verdict}")

    print(f"{'-' * 76}")
    print(f"\nFP summary")
    print(f"  Total anomaly alarms on benign data   : {total_fp_alarms}")
    print(f"  Entities affected                     : "
          f"{len(entity_rule_map)} of {n_entities}")
    print(f"  FP rate (alarms / entity / day)       : {fp_per_entity_per_day:.4f}")
    print(f"  NEVER-FIRE rules that fired           : {never_fire_fired}")

    if never_fire_fired > 0:
        print(f"\n  *** WARNING: {never_fire_fired} NEVER-FIRE alarm(s) on benign data. ***")
        print("      This indicates a bug in generate_baseline_events() where a benign")
        print("      event description contains an attack keyword.  Inspect below.")
    else:
        print("\n  All NEVER-FIRE rules correctly silent on benign data.")

    # -- Step 8: per-entity breakdown ------------------------------------------
    if entity_rule_map:
        print(f"\n{'-' * 76}")
        print("Per-entity breakdown (entities that triggered at least one rule)")
        print(f"{'-' * 76}")
        for entity in sorted(entity_rule_map.keys()):
            rule_dict = entity_rule_map[entity]
            total_for_entity = sum(len(v) for v in rule_dict.values())
            print(f"\n  Entity: {entity!r}  ({total_for_entity} alarm(s))")
            for atype, descs in sorted(rule_dict.items()):
                print(f"    Rule : {atype}")
                for d in descs[:2]:          # show at most 2 instances per rule
                    print(f"    Desc : {d[:110]}..." if len(d) > 110 else f"    Desc : {d}")
                if len(descs) > 2:
                    print(f"           ... and {len(descs) - 2} more instance(s)")
    else:
        print("\n  No entities triggered any rules on the benign baseline. (Ideal.)")

    # -- Step 9: key insight ---------------------------------------------------
    print(f"\n{'=' * 76}")
    print("Key insight")
    print(f"{'-' * 76}")
    print(
        "  STATISTICAL rules (hourly_event_spike) use a per-user Z-score.\n"
        "  By the properties of the normal distribution, ~2.5% of user-hours\n"
        "  are expected to exceed Z > 2.5 in any large benign dataset.  This\n"
        "  is NOT a bug -- it is the designed operating point of the detector.\n"
        "  At this threshold the detector catches genuine bursts (e.g. a malware\n"
        "  C2 poll loop) while keeping the benign alarm rate manageable.\n"
        "\n"
        "  NEVER-FIRE rules (mimikatz_invocation, shadow_copy_deletion,\n"
        "  boot_recovery_disabled, encoded_powershell, etc.) match specific\n"
        "  forensic keywords that are NEVER present in legitimate enterprise\n"
        "  activity.  Any firing on the benign baseline is a genuine defect in\n"
        "  either the rule or the event generator.\n"
        "\n"
        "  BEHAVIORAL rules (smb_lateral_movement, lateral_velocity,\n"
        "  lsass_pth_correlation, rdp_lateral_movement) may fire at a very low\n"
        "  rate on help-desk or IT-admin activity.  A rate below 0.01 alarms\n"
        "  per entity per day is acceptable for high-value detections.\n"
    )
    print(f"{'=' * 76}")
    print()


if __name__ == "__main__":
    main()

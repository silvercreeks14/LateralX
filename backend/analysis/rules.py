def generate_yara_rules(
    iocs: list[IOC],
    techniques: list[MitreTechnique],
) -> list[str]:
    """
    Return YARA rule strings.

    Two categories:
    - Hash rules: one rule per unique MD5/SHA256 IOC, matching by file hash.
    - Behavioral rules: one rule per detected MITRE technique ID that has a
      known behavioral string-match pattern in _YARA_TECH_PATTERNS.
    """
    rules: list[str] = []

    # ── Hash-based file rules ─────────────────────────────────────────────────
    hashes: dict[str, list[str]] = {"md5": [], "sha256": []}
    for ioc in iocs:
        if ioc.type == "md5":
            hashes["md5"].append(ioc.value)
        elif ioc.type == "sha256":
            hashes["sha256"].append(ioc.value)

    if hashes["md5"] or hashes["sha256"]:
        cond_parts: list[str] = []
        if hashes["md5"]:
            md5_list = ", ".join(f'"{h}"' for h in hashes["md5"][:20])
            cond_parts.append(f"hash.md5(0, filesize) in ({md5_list})")
        if hashes["sha256"]:
            sha_list = ", ".join(f'"{h}"' for h in hashes["sha256"][:20])
            cond_parts.append(f"hash.sha256(0, filesize) in ({sha_list})")
        condition = " or\n        ".join(cond_parts)
        rules.append(
            f'import "hash"\n\n'
            f"rule LateralX_IOC_File_Hash\n{{\n"
            f"    meta:\n"
            f'        description = "File hash IOC match — extracted from LateralX incident analysis"\n'
            f'        author      = "LateralX Auto-Generator"\n'
            f'        severity    = "high"\n'
            f"    condition:\n"
            f"        {condition}\n"
            f"}}"
        )

    # ── Behavioral technique rules ────────────────────────────────────────────
    seen_techs: set[str] = set()
    for tech in techniques:
        tech_id = tech.id
        # Also check parent technique (e.g. T1003 for T1003.001)
        candidates = {tech_id, tech_id.split(".")[0]}
        for tid in candidates:
            if tid in seen_techs or tid not in _YARA_TECH_PATTERNS:
                continue
            seen_techs.add(tid)
            rule_name, description, strings = _YARA_TECH_PATTERNS[tid]
            str_defs = "\n".join(
                f"        $s{i} = {s}" for i, s in enumerate(strings)
            )
            str_cond = " or ".join(f"$s{i}" for i in range(len(strings)))
            rules.append(
                f"rule {rule_name}\n{{\n"
                f"    meta:\n"
                f'        description = "{description}"\n'
                f'        author      = "LateralX Auto-Generator"\n'
                f'        mitre_id    = "{tid}"\n'
                f'        severity    = "high"\n'
                f"    strings:\n"
                f"{str_defs}\n"
                f"    condition:\n"
                f"        {str_cond}\n"
                f"}}"
            )

    return rules


def generate_firewall_rules(iocs: list[IOC]) -> list[str]:
    """
    Return firewall blocking rules in three formats for each malicious IP IOC:
      - iptables (Linux)
      - Windows Firewall (netsh advfirewall)
      - Cisco ACL (extended access-list deny)
    One group of three rules per unique external IP.
    """
    rules: list[str] = []
    seen: set[str] = set()
    _RFC1918 = ("10.", "192.168.", "172.16.", "172.17.", "172.18.", "172.19.",
                "172.20.", "172.21.", "172.22.", "172.23.", "172.24.", "172.25.",
                "172.26.", "172.27.", "172.28.", "172.29.", "172.30.", "172.31.")

    for ioc in iocs:
        if ioc.type not in ("ip", "ip_address", "src_ip", "dst_ip"):
            continue
        ip = ioc.value.strip()
        if not ip or ip in seen:
            continue
        if any(ip.startswith(pfx) for pfx in _RFC1918):
            continue
        seen.add(ip)
        ctx = (ioc.context or "")[:60]
        rules.append(f"# Block {ip} — {ctx}")
        rules.append(f"iptables -I INPUT -s {ip} -j DROP && iptables -I OUTPUT -d {ip} -j DROP")
        rules.append(
            f'netsh advfirewall firewall add rule name="LateralX_BLOCK_{ip}" '
            f'dir=in action=block remoteip={ip}'
        )
        rules.append(f"ip access-list extended LATERALX_BLOCK\n  deny ip host {ip} any\n  deny ip any host {ip}")
        rules.append("")

    return rules


def generate_detection_rules_from_techniques_only(result: RCAResult) -> str:
    """
    Lightweight detection-rules HTML fragment for quick scan reports.
    Generates Sigma and YARA from stored IOCs and techniques — no event
    timeline required, so no Snort or behavioral rules are included.
    Uses the same CSS class names as report.py (_CSS) so it embeds cleanly.
    """
    sigma_rules = generate_sigma_rules(result.iocs, result.mitre_techniques)
    yara_rules  = generate_yara_rules(result.iocs, result.mitre_techniques)

    if not sigma_rules and not yara_rules:
        return ""

    note = (
        '<div style="background:#f0f9ff;border:1px solid #bae6fd;border-radius:6px;'
        'padding:10px 14px;margin-bottom:16px;font-size:12px;color:#0c4a6e">'
        'Quick scan — Sigma and YARA only. '
        'Run full analysis for network and firewall rules.</div>'
    )

    _sigma_fallback = '<p style="color:#64748b;font-size:12px">No Sigma rules generated.</p>'
    _yara_fallback  = '<p style="color:#64748b;font-size:12px">No YARA rules generated.</p>'

    sigma_entries = ""
    for r in sigma_rules[:12]:
        tags_str = ", ".join(r.get("tags", []))
        kw_str   = str(r["detection"].get("keywords", []))
        sigma_entries += (
            f'<div class="rule-entry">'
            f'<span style="color:#7dd3fc">title:</span> {r["title"]}\n'
            f'<span style="color:#7dd3fc">id:</span> {r["id"]}\n'
            f'<span style="color:#7dd3fc">tags:</span> {tags_str}\n'
            f'<span style="color:#86efac">detection:</span>\n'
            f'  keywords: {kw_str}'
            f'</div>'
        )

    yara_entries = "".join(
        f'<div class="rule-entry">{rule}</div>' for rule in yara_rules[:10]
    )

    sigma_col = (
        f'<div class="rule-block"><h4>Sigma Rules ({len(sigma_rules)} generated)</h4>'
        f'{sigma_entries or _sigma_fallback}'
        f'</div>'
    )
    yara_col = (
        f'<div class="rule-block"><h4>YARA Rules ({len(yara_rules)} generated)</h4>'
        f'{yara_entries or _yara_fallback}'
        f'</div>'
    )

    title = (
        f"Detection Rules — Sigma ({len(sigma_rules)}) · "
        f"YARA ({len(yara_rules)}) · Quick Scan"
    )
    body = note + f'<div class="rules-wrap">{sigma_col}{yara_col}</div>'
    return f'<div class="sec" data-ai-generated="false"><h2>{title}</h2>{body}</div>'


def rules_to_text(sigma_rules: list[dict], snort_rules: list[str], yara_rules: list[str] | None = None) -> str:
    """Produce a combined human-readable block for display or copy-paste."""
    lines: list[str] = []

    if sigma_rules:
        lines.append("# ── Sigma Rules ──────────────────────────────────────────────")
        for r in sigma_rules:
            lines.append(f"\ntitle: {r['title']}")
            lines.append(f"id: {r['id']}")
            lines.append(f"status: {r['status']}")
            lines.append(f"description: {r['description']}")
            lines.append("logsource:")
            for k, v in r["logsource"].items():
                lines.append(f"  {k}: {v}")
            lines.append("detection:")
            for kw in r["detection"]["keywords"]:
                lines.append(f"  keywords:\n    - {kw}")
            lines.append(f"  condition: {r['detection']['condition']}")
            lines.append(f"level: {r['level']}")
            lines.append(f"tags: {r['tags']}")
            lines.append("---")

    if yara_rules:
        lines.append("\n# ── YARA Rules ───────────────────────────────────────────────")
        lines.extend(yara_rules)

    if snort_rules:
        lines.append("\n# ── Snort / Suricata Rules ───────────────────────────────────")
        lines.extend(snort_rules)

    return "\n".join(lines)
